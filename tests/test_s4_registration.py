"""S4 pre-registration: the registered-runs file, the S4 experiment config and the checks a formal run must pass.

The registered file (configs/experiments/s4_runs_20261110.json) is generated by scripts.training.register_runs;
these tests fail when it drifts from the configs, when the S4 config stops following the S3 decisions, or when the
pre-registration document no longer lists the hashes the runs will be checked against.
"""
import copy
import importlib.util
import json
from pathlib import Path

import pytest

from src.training import registry
from src.training.protocol_v3 import protocol_id
from src.training.rl_config import read_json, registered_runs, resolve

ROOT = Path(__file__).resolve().parents[1]
LEDGER = ROOT / "configs/experiments/s4_runs_20261110.json"
S4 = ROOT / "configs/experiments/rl_v3_p1_20261110.json"
RL_V3 = ROOT / "configs/experiments/rl_v3.json"
ARMS = ROOT / "configs/experiments/arms.json"
DECISIONS = ROOT / "configs/experiments/s3_decisions_20261110.json"
RUNTIME = ROOT / "configs/experiments/runtime_frozen_20261109.json"
PREREGISTRATION = ROOT / "docs/plan/S4预注册_20261110.md"
ORDER = [("rl_v5", 1), ("rl_ans", 1), ("rl_blind", 1), ("rl_v4", 1), ("rl_v5_placebo", 1),
         ("rl_v5", 2), ("rl_ans", 2), ("rl_blind", 2), ("rl_v4", 2), ("rl_v5_placebo", 2),
         ("rl_v5", 3), ("rl_ans", 3)]


def ledger():
    return read_json(LEDGER)


def flat(d, prefix=""):
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flat(v, prefix + k + "."))
        else:
            out[prefix + k] = v
    return out


def test_registered_file_is_generated_from_the_configs():
    """Every hash, run name, output directory and step budget equals what register_runs --write computes."""
    current = ledger()
    assert registry.derive(current, ROOT) == current


def test_registered_order_covers_every_run_once_seed_major():
    current = ledger()
    assert [(e["arm"], e["seed"]) for e in current["runs"]] == ORDER
    assert sorted(ORDER) == sorted(registered_runs(ARMS))
    assert [(e["arm"], e["seed"]) for e in current["optional_runs"]] == [("rl_v5_groupnorm", 1), ("rl_v5_groupnorm", 2)]
    assert all(e["max_steps"] == 228 for e in registry.entries(current))  # floor(3 epochs x 609 rows / 8 prompts)
    assert len({e["config_sha256"] for e in registry.entries(current)}) == 14
    broken = copy.deepcopy(current)
    broken["runs"] = broken["runs"][:-1]
    with pytest.raises(ValueError, match="exactly once"):
        registry.validate(broken, ROOT)
    broken = copy.deepcopy(current)
    broken["runs"][0]["order"] = 7
    with pytest.raises(ValueError, match="order"):
        registry.validate(broken, ROOT)


def test_s4_config_follows_the_s3_decisions():
    decisions = read_json(DECISIONS)
    current = ledger()
    assert registry.sha256_file(DECISIONS) == current["decisions"]["sha256"]
    assert decisions["complete"] and all(decisions["inputs"].values())
    s4, runtime = read_json(S4), read_json(RUNTIME)
    assert s4["protocol"] == protocol_id(decisions["prompt"]["chosen"]) == current["protocol"] == protocol_id("p1")
    assert decisions["warmup"]["needed"] is False  # no warm-up stage: every arm starts from V0
    assert decisions["max_completion_length"]["decided"]
    assert s4["train"]["max_completion_length"] == decisions["max_completion_length"]["value"] == 1024
    assert runtime["generation_backend"] == decisions["generation_backend"]["value"] == "vllm"
    assert decisions["generation_backend"]["passed"]
    assert s4["model"]["max_pixels"] == decisions["resolution"]["max_pixels"] == 802816


def test_s4_config_differs_from_rl_v3_only_in_name_protocol_and_output_root():
    diff = {k for k, v in flat(read_json(S4)).items() if flat(read_json(RL_V3)).get(k) != v}
    assert diff == {"name", "protocol", "output_root"}
    assert set(flat(read_json(S4))) == set(flat(read_json(RL_V3)))


def test_s4_arms_differ_only_in_declared_factors():
    current = ledger()
    resolved = {e["arm"]: registry.resolve_registered(current, e["arm"], e["seed"], ROOT)
                for e in registry.entries(current) if e["seed"] == 1}
    reference = flat(resolved["rl_ans"])
    allowed = {"arm.name", "arm.perception_reward", "arm.perception_weight", "arm.train_with_image", "arm.metadata",
               "train.scale_rewards", "run_name", "output_dir", "config_sha256"}
    for arm, config in resolved.items():
        diff = {k for k, v in flat(config).items() if reference.get(k) != v}
        assert diff <= allowed, (arm, diff - allowed)
        assert config["smoke"] == {} and config["train"]["gradient_accumulation_steps"] == 8


