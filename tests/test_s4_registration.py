def test_pilot_runs_and_gates():
    from scripts.colab import decide_s3
    from src.training.rl_config import SMOKE_KEYS

    pilot = ledger()["pilot"]
    gates = pilot["gates"]
    g1 = gates["G1_importance_sampling"]
    assert (g1["ratio_mean_min"], g1["ratio_mean_max"]) == decide_s3.IS_RANGE  # the D41 rule, unchanged
    assert g1["logp_difference_mean_max"] == decide_s3.LOGP_LIMIT
    assert gates["G6_protocol"]["rollout_protocol"] == protocol_id("p1")
    assert gates["G6_protocol"]["max_prompt_tokens"] == read_json(S4)["train"]["max_prompt_tokens"]
    runs = [pilot["learning_run"], pilot["learning_retry"], pilot["resume_run"], *pilot["arm_runs"]]
    assert {r["arm"] for r in pilot["arm_runs"]} | {"rl_v5"} == {"rl_ans", "rl_v4", "rl_v5", "rl_v5_placebo", "rl_blind"}
    for run in runs:
        assert set(run["smoke"]) <= SMOKE_KEYS
        config = resolve(S4, run["arm"], pilot["seed"], smoke=run["smoke"], n_rows=609)
        assert config["run_name"].endswith("_smoke")  # pilot runs are engineering checks, never results
    assert pilot["learning_run"]["smoke"]["max_steps"] >= 2 * gates["G4_learning"]["window_steps"]


def test_registration_check_reports_every_difference():
    current = ledger()
    expected = registry.expectation(current, "rl_v5", 1)
    config = registry.resolve_registered(current, "rl_v5", 1, ROOT)
    data = dict(current["data_sha256"])
    assert registry.check(expected, config, data, 609, "NVIDIA A100-SXM4-40GB") == []
    changed = copy.deepcopy(config)
    changed["train"]["learning_rate"] = 2e-5
    changed["config_sha256"] = "f" * 64
    problems = registry.check(expected, dict(changed, smoke={"max_steps": 3}), dict(data, train_file="0" * 64), 608,
                              "NVIDIA L4")
    assert len(problems) == 5, problems
    assert registry.check(expected, registry.resolve_registered(current, "rl_ans", 1, ROOT), data, 609,
                          "NVIDIA A100-SXM4-40GB")
    with pytest.raises(ValueError, match="not a registered run"):
        registry.expectation(current, "rl_v5", 4)
    assert registry.expectation(current, "rl_v5_groupnorm", 2)["optional"] is True


def test_show_prints_the_registered_config_of_a_run(capsys):
    from scripts.training import register_runs

    assert register_runs.main(["--show", "rl_v5_placebo", "2"]) == 0
    printed = json.loads(capsys.readouterr().out)
    assert printed["config_sha256"] == registry.find(ledger(), "rl_v5_placebo", 2)["config_sha256"]
    assert printed["arm"]["metadata"] == "placebo" and printed["seed"] == 2
    assert printed["protocol"] == protocol_id("p1") and printed["train"]["max_steps"] == 228
    with pytest.raises(ValueError, match="not a registered run"):
        register_runs.main(["--show", "rl_blind", "3"])


def test_train_rl_refuses_overrides_for_registered_runs(tmp_path, capsys):
    from scripts.training import train_rl

    base = ["--registered", str(LEDGER), "--arm", "rl_v5", "--seed", "1"]
    other_runtime = tmp_path / "runtime.json"
    other_runtime.write_text(json.dumps(dict(read_json(RUNTIME), per_device_train_batch_size=4)), encoding="utf-8")
    cases = [(["--smoke", "max_steps=3"], "--smoke is not allowed"),
             (["--output-dir", str(tmp_path / "x")], "--output-dir is not allowed"),
             (["--experiment", str(RL_V3)], "differs from the registered"),
             (["--runtime", str(other_runtime)], "differs from the registered"),
             (["--seed", "4"], "not a registered run")]
    for extra, message in cases:
        argv = base + extra if extra[0] != "--seed" else base[:-2] + extra
        with pytest.raises(SystemExit):
            train_rl.main(argv)
        assert message in capsys.readouterr().err, extra


def test_preregistration_lists_every_registered_hash():
    text = PREREGISTRATION.read_text(encoding="utf-8")
    current = ledger()
    for entry in registry.entries(current):
        assert entry["config_sha256"] in text, entry["run_name"]
    assert current["decisions"]["sha256"] in text and current["runtime"]["content_sha256"] in text
    for value in current["data_sha256"].values():
        assert value[:16] in text


